      "$td/twin-$n.json" > "$td/reply-$n.txt" 2>> "$sb/_stderr.log" || cp /dev/null "$td/reply-$n.txt"
  printf 'Аналитик:\n%s\n\n' "$(cat "$td/reply-$n.txt")" >> "$td/dialog.md"
