twin_reply() {
  local sb="$1" last="$2" n="$3" td="$1/_twin" wd
  mkdir -p "$td"
  [ -s "$td/dialog.md" ] || printf 'Аналитик:\n%s\n\n' "$(cat "$PROMPT")" > "$td/dialog.md"
